'use strict';

/**
 * Fixture invariants for the three committed workbooks.
 *
 * The file pins each workbook's row count, its `Student ID` key set, the
 * header cells the loaders validate, the ZIP container integrity the reader
 * verifies, and its own SHA-256. A binary fixture produces no reviewable diff,
 * so its digest is its only drift detector, and equally the proof that the
 * feature changed no byte of it.
 *
 * The container assertions are deliberately made WITHOUT `lib/workbook.js`:
 * they walk the ZIP records themselves, so they state a fact about the
 * committed bytes rather than about the reader, which is what makes the
 * reader's own integrity checks - local header against central record, and the
 * recorded CRC-32 against the inflated data - meaningful rather than vacuous. A
 * workbook regenerated by a tool that stores no checksum fails here, naming the
 * missing field, instead of surfacing as an unexplained startup failure.
 *
 * All four tests are top level, with no subtest, `describe`, `it` or hook: the
 * guarded runner counts passing tests against a fixed floor, and an assertion
 * made inside a hook is not counted at all, so multi-case behaviour goes in a
 * case table inside a test body. Every assertion is a pure read - no socket,
 * no child process, no write of any kind - so nothing needs tearing down, and
 * the contents of `activities.json` are not this file's subject.
 */

